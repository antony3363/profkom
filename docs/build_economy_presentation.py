# ---------- palette ----------
DARK = RGBColor(0x1B, 0x1F, 0x2A)
ACCENT = RGBColor(0x2F, 0x5D, 0xC7)
ACCENT_LIGHT = RGBColor(0xEA, 0xF0, 0xFC)
GREEN = RGBColor(0x1E, 0x8E, 0x3E)
GREEN_BG = RGBColor(0xE9, 0xF7, 0xEE)
RED = RGBColor(0xC5, 0x22, 0x1F)
RED_BG = RGBColor(0xFD, 0xEC, 0xEC)
GRAY = RGBColor(0x5F, 0x63, 0x6E)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)

SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)

prs = Presentation()
prs.slide_width = SLIDE_W
prs.slide_height = SLIDE_H
BLANK = prs.slide_layouts[6]


def add_slide():
    return prs.slides.add_slide(BLANK)


def set_background(slide, color):
    bg = slide.background
    bg.fill.solid()
    bg.fill.fore_color.rgb = color


def add_rect(slide, x, y, w, h, color, line=False):
    shp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    shp.fill.solid()
    shp.fill.fore_color.rgb = color
    if line:
        shp.line.color.rgb = color
        shp.line.width = Pt(0.5)
    else:
        shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def add_text(slide, x, y, w, h, text, size=18, color=DARK, bold=False,
             align=PP_ALIGN.LEFT, font="Segoe UI", anchor=MSO_ANCHOR.TOP,
             italic=False):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    run.font.name = font
    return tb


def add_bullets(slide, x, y, w, h, items, size=15, color=DARK, font="Segoe UI",
                 space_after=8, marker="•  "):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(space_after)
        run = p.add_run()
        run.text = marker + item
        run.font.size = Pt(size)
        run.font.color.rgb = color
        run.font.name = font
    return tb


def slide_header(slide, kicker, title):
    add_rect(slide, 0, 0, SLIDE_W, Inches(1.35), ACCENT)
    add_text(slide, Inches(0.6), Inches(0.12), Inches(12), Inches(0.4),
              kicker, size=14, color=RGBColor(0xD8, 0xE4, 0xFB), bold=True)
    add_text(slide, Inches(0.6), Inches(0.45), Inches(12), Inches(0.8),
              title, size=28, color=WHITE, bold=True)


def pros_cons_slide(kicker, title, mechanics, pros, cons, note=None):
    slide = add_slide()
    set_background(slide, WHITE)
    slide_header(slide, kicker, title)

    y0 = Inches(1.55)
    if mechanics:
        add_text(slide, Inches(0.6), y0, Inches(12.1), Inches(0.75),
                  "Механика: " + mechanics, size=15, color=GRAY, italic=True)
        y0 = y0 + Inches(0.75)

    col_w = Inches(5.85)
    gap = Inches(0.3)
    col_h = Inches(4.6)
    x_left = Inches(0.6)
    x_right = x_left + col_w + gap

    # pros column
    add_rect(slide, x_left, y0, col_w, Inches(0.5), GREEN)
    add_text(slide, x_left + Inches(0.2), y0 + Inches(0.05), col_w - Inches(0.4), Inches(0.4),
              "+  Плюсы", size=17, color=WHITE, bold=True)
    add_rect(slide, x_left, y0 + Inches(0.5), col_w, col_h, GREEN_BG)
    add_bullets(slide, x_left + Inches(0.25), y0 + Inches(0.65), col_w - Inches(0.5), col_h - Inches(0.3),
                pros, size=15, color=DARK)

    # cons column
    add_rect(slide, x_right, y0, col_w, Inches(0.5), RED)
    add_text(slide, x_right + Inches(0.2), y0 + Inches(0.05), col_w - Inches(0.4), Inches(0.4),
              "−  Минусы", size=17, color=WHITE, bold=True)
    add_rect(slide, x_right, y0 + Inches(0.5), col_w, col_h, RED_BG)
    add_bullets(slide, x_right + Inches(0.25), y0 + Inches(0.65), col_w - Inches(0.5), col_h - Inches(0.3),
                cons, size=15, color=DARK)

    if note:
        add_text(slide, Inches(0.6), Inches(7.0), Inches(12.1), Inches(0.4),
                  note, size=12, color=GRAY, italic=True)
    return slide


def section_slide(number, title, subtitle):
    slide = add_slide()
    set_background(slide, DARK)
    add_text(slide, Inches(0.9), Inches(2.7), Inches(3.2), Inches(1.6),
              number, size=90, color=ACCENT, bold=True)
    add_text(slide, Inches(4.1), Inches(2.9), Inches(8.4), Inches(1.2),
              title, size=34, color=WHITE, bold=True)
    add_text(slide, Inches(4.1), Inches(3.9), Inches(8.4), Inches(1.5),
              subtitle, size=17, color=RGBColor(0xB9, 0xC3, 0xD9))
    return slide


